local T = require("tests.testlib")
local function setup()
    local G = {}
    for _, file in ipairs({ "Constants", "CharacterIdentity", "GearData", "GearSnapshot", "Storage", "SyncProtocol", "SyncTransport", "GuildSync" }) do
        T.loadAddonFile("The Guild Book gear/" .. file .. ".lua", G)
    end
    return G, assert(G.InitializeGearDatabase()), { key = "Alice-Realm", name = "Alice", realm = "Realm", guid = "Player-1" }
end
local function snapshot(G, at, base)
    local s = { complete = true, capturedAt = at, slots = {} }
    for _, slot in ipairs(G.TRACKED_SLOTS) do
        s.slots[slot.key] = { inventorySlotID = slot.inventorySlotID, itemID = base + slot.inventorySlotID, itemLink = "|Hitem:" .. (base + slot.inventorySlotID) .. "|h[Gear]|h" }
    end
    return s
end
local function changed(id, slot)
    return { inventorySlotID = slot or 1, itemID = id, itemLink = "|Hitem:" .. id .. "|h[Gear]|h" }
end
T.test("new complete observations replace gear without manufacturing an owner sequence", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 100, 1000), 8))
    T.assertTrue(G.SaveObservedCharacterRecord(db, who, snapshot(G, 200, 2000)))
    T.assertEqual(db.characters[who.key].confirmedSequence, 8)
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:2001")
    assert(G.SaveReceivedCompleteCharacterRecord(db, who, snapshot(G, 250, 3000), 1))
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:3001")
    T.assertEqual(db.characters[who.key].confirmedSequence, 8)
end)
T.test("older higher sequence snapshots cannot overwrite a newer complete observation", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 200, 2000), 0))
    assert(G.SaveReceivedCompleteCharacterRecord(db, who, snapshot(G, 100, 1000), 40))
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:2001")
    T.assertEqual(db.characters[who.key].gear.capturedAt, 200)
    T.assertEqual(db.characters[who.key].confirmedSequence, 40)
end)
T.test("delayed owner updates covered by inspection advance ordering without regressing gear", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 200, 2000), 0))
    assert(G.ApplyReceivedCharacterSlot(db, who.key, "HEAD", changed(9999), 150, 40))
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:2001")
    T.assertTrue(db.characters[who.key].complete)
    assert(G.ApplyReceivedCharacterSlot(db, who.key, "HEAD", changed(9998), 210, 41))
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:9998")
end)
T.test("slot freshness is independent and survives storage and protocol relays", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 100, 1000), 0))
    assert(G.ApplyReceivedCharacterSlot(db, who.key, "HEAD", changed(9999), 300, 1))
    assert(G.ApplyReceivedCharacterSlot(db, who.key, "NECK", changed(9998, 2), 200, 2))
    local gear = db.characters[who.key].gear
    T.assertEqual(gear.capturedAt, 300)
    T.assertEqual(gear.slotObservedAt[1], 300)
    T.assertEqual(gear.slotObservedAt[2], 200)
    T.assertEqual(gear.slotObservedAt[3], 100)
    local runtime = assert(G.BuildRuntimeGearSnapshot({}, gear))
    local payload = assert(G.EncodeSyncSnapshotResponse(who, who, who, runtime, 2, "000001"))
    local response = assert(G.DecodeSyncMessage(payload))
    T.assertEqual(response.snapshot.slotObservedAt[1], 300)
    T.assertEqual(response.snapshot.slotObservedAt[2], 200)
    T.assertEqual(response.snapshot.slotObservedAt[3], 100)
    local other = assert(G.InitializeGearDatabase())
    assert(G.SaveReceivedCompleteCharacterRecord(other, who, response.snapshot, 2))
    assert(G.SaveReceivedCompleteCharacterRecord(other, who, snapshot(G, 250, 2000), 0))
    T.assertEqual(other.characters[who.key].gear.slots[1], "item:9999")
    T.assertEqual(other.characters[who.key].gear.slots[2], "item:2002")
    T.assertEqual(other.characters[who.key].gear.slotObservedAt[3], 250)
end)
T.test("inspection repairs a gap only if its full observation covers the missed update", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 100, 1000), 4))
    local ok, err = G.ApplyReceivedCharacterSlot(db, who.key, "HEAD", changed(9999), 200, 8)
    T.assertFalse(ok); T.assertEqual(err, "confirmed-sequence-gap")
    T.assertFalse(G.SaveReceivedCompleteCharacterRecord(db, who, snapshot(G, 150, 1500), 0))
    T.assertTrue(db.characters[who.key].refreshNeeded)
    assert(G.SaveObservedCharacterRecord(db, who, snapshot(G, 250, 2000)))
    T.assertTrue(db.characters[who.key].complete)
    T.assertNil(db.characters[who.key].refreshNeeded)
    T.assertEqual(db.characters[who.key].confirmedSequence, 8)
end)
T.test("empty slot observations block older equipped gear and retain equal-second network observations", function()
    local G, db, who = setup()
    local fresh = snapshot(G, 200, 2000)
    fresh.slots.HEAD = { inventorySlotID = 1, itemID = false, itemLink = false }
    assert(G.SaveObservedCharacterRecord(db, who, fresh))
    assert(G.SaveReceivedCompleteCharacterRecord(db, who, snapshot(G, 200, 1000), 5))
    T.assertNil(db.characters[who.key].gear.slots[1])
    assert(G.SaveObservedCharacterRecord(db, who, snapshot(G, 200, 3000)))
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:3001")
end)
T.test("observation metadata rejects malformed maps without mutating saved gear", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 100, 1000)))
    for _, invalid in ipairs({ false, { [1] = 201 }, { [20] = 100 }, { [1] = -1 }, { [1] = 0/0 } }) do
        local bad = snapshot(G, 200, 2000)
        bad.slotObservedAt = invalid
        T.assertFalse(G.SaveReceivedCompleteCharacterRecord(db, who, bad, 5))
        T.assertEqual(db.characters[who.key].gear.slots[1], "item:1001")
    end
end)
T.test("claims carry latest and complete observation freshness", function()
    local G, _, who = setup()
    local payload = assert(G.EncodeSyncSnapshotResponseClaim(who, who, who, 0, "000001", 250, 100))
    local message = assert(G.DecodeSyncMessage(payload))
    T.assertEqual(message.observedAt, 250)
    T.assertEqual(message.baselineObservedAt, 100)
end)

T.test("a fresh inspection repairs a legacy saved gap without observation metadata", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 100, 1000), 4))
    G.ApplyReceivedCharacterSlot(db, who.key, "HEAD", changed(9999), 200, 8)
    db.characters[who.key].requiredBaselineObservedAt = nil
    T.assertTrue(G.SaveObservedCharacterRecord(db, who, snapshot(G, 250, 2000)))
    T.assertTrue(db.characters[who.key].complete)
    T.assertEqual(db.characters[who.key].confirmedSequence, 8)
end)
T.test("invalid saved gap observation metadata fails closed", function()
    local G, db, who = setup()
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 100, 1000), 4))
    G.ApplyReceivedCharacterSlot(db, who.key, "HEAD", changed(9999), 200, 8)
    db.characters[who.key].requiredBaselineObservedAt = false
    local record, err = G.GetCharacterRecord(db, who.key)
    T.assertNil(record)
    T.assertEqual(err, "record-incomplete-invalid")
end)

T.test("inspection and sync realm aliases merge into the same saved character", function()
    local G, db, who = setup()
    who.realm, who.key = "Some Realm", "Alice-Some Realm"
    assert(G.SaveCompleteCharacterRecord(db, who, snapshot(G, 100, 1000), 4))
    local alias = { key = "Alice-SomeRealm", name = "Alice", realm = "SomeRealm", guid = who.guid }
    assert(G.SaveObservedCharacterRecord(db, alias, snapshot(G, 200, 2000)))
    T.assertNil(db.characters[alias.key])
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:2001")
    assert(G.ApplyReceivedCharacterSlot(db, alias.key, "HEAD", changed(9999), 300, 5))
    T.assertEqual(db.characters[who.key].gear.slots[1], "item:9999")
    assert(G.SaveReceivedCompleteCharacterRecord(db, alias, snapshot(G, 400, 4000), 6))
    T.assertNil(db.characters[alias.key])
    T.assertEqual(db.characters[who.key].identity.key, who.key)
end)

T.test("snapshot latest observation cannot exceed every explicit slot observation", function()
    local G, db, who = setup()
    local inflated = snapshot(G, 999, 1000)
    inflated.slotObservedAt = {}
    for _, slot in ipairs(G.TRACKED_SLOTS) do inflated.slotObservedAt[slot.inventorySlotID] = 100 end
    T.assertFalse(G.SaveReceivedCompleteCharacterRecord(db, who, inflated, 1))
    T.assertNil(db.characters[who.key])
    local payload = G.EncodeSyncSnapshotResponse(who, who, who, inflated, 1, "000001")
    T.assertNil(payload)
end)
